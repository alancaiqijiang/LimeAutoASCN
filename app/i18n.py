def normalize_lang(value: str | None) -> str | None:
    if not value:
        return None
    lowered = value.strip().lower().replace("_", "-")
    if lowered in SUPPORTED_LANGS:
        return lowered
    if lowered.startswith("zh"):
        return "zh"
    if lowered.startswith("en"):
        return "en"
    return None


def current_lang() -> str:
    return _current_lang.get()


def bind_lang(lang: str) -> Token:
    return _current_lang.set(normalize_lang(lang) or DEFAULT_LANG)


def reset_lang(token: Token) -> None:
    _current_lang.reset(token)


def resolve_lang(request: Request) -> str:
    query_lang = normalize_lang(request.query_params.get("lang"))
    if query_lang:
        return query_lang
    cookie_lang = normalize_lang(request.cookies.get(LANG_COOKIE))
    if cookie_lang:
        return cookie_lang
    accept = request.headers.get("accept-language", "")
    for part in accept.split(","):
        tagged = normalize_lang(part.split(";")[0])
        if tagged:
            return tagged
    return DEFAULT_LANG


def language_href(request: Request, lang: str) -> str:
    params = [(key, value) for key, value in request.query_params.multi_items() if key != "lang"]
    params.append(("lang", lang))
    return f"{request.url.path}?{urlencode(params)}"


def tr(key: str, **kwargs: Any) -> str:
    lang = current_lang()
    table = STRINGS[lang]
    if lang == "en" and "n" in kwargs:
        try:
            if int(kwargs["n"]) != 1 and f"{key}_plural" in table:
                key = f"{key}_plural"
        except (TypeError, ValueError):
            pass
    text = table.get(key) or STRINGS[DEFAULT_LANG][key]
    return text.format(**kwargs) if kwargs else text


def public_error(message: str) -> str:
    key = ERROR_KEYS.get(message)
    return tr(key) if key else message


class Translator:
    def __init__(self, lang: str) -> None:
        self.lang = lang

    def __getattr__(self, key: str) -> str:
        if key.startswith("_") or key == "jinja_pass_arg":
            raise AttributeError(key)
        return tr(key)

    def __call__(self, key: str, **kwargs: Any) -> str:
        return tr(key, **kwargs)


def translator(lang: str | None = None) -> Translator:
    return Translator(lang or current_lang())


def template_context(request: Request) -> dict[str, Any]:
    lang = getattr(request.state, "lang", None) or resolve_lang(request)
    return {
        "lang": lang,
        "html_lang": HTML_LANG[lang],
        "t": translator(lang),
        "lang_href_zh": language_href(request, "zh"),
        "lang_href_en": language_href(request, "en"),
    }
